-- Inventaires du stock (maker / checker Moyens Généraux)
--
-- Tables inventaire, inventaire_ligne, inventaire_evenement ; colonne stock_mere.id_inventaire
-- (en-tête des mouvements qui passent les écarts d'un inventaire validé) ; vue de l'historique
-- des mouvements : un ajustement d'inventaire y apparaît à la date de validation, avec la
-- référence INV-… et le valideur.
--
-- En PREPROD, Hibernate (ddl-auto=update) crée les tables et la colonne au démarrage ;
-- seule la vue doit être remplacée. En PROD : exécuter le script en entier, avant ou après
-- le déploiement. Rejouable.
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

CREATE TABLE IF NOT EXISTS inventaire (
    id_inventaire  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    reference      VARCHAR(30),
    id_famille     INTEGER,
    statut         VARCHAR(20)  NOT NULL,
    commentaire    TEXT,
    id_cree_par    INTEGER      NOT NULL,
    date_ouverture TIMESTAMP    NOT NULL,
    id_soumis_par  INTEGER,
    date_soumission TIMESTAMP,
    id_valide_par  INTEGER,
    date_cloture   TIMESTAMP,
    motif_rejet    TEXT,
    CONSTRAINT inventaire_pkey PRIMARY KEY (id_inventaire),
    CONSTRAINT uk_inventaire_reference UNIQUE (reference),
    CONSTRAINT inventaire_statut_check CHECK (statut IN ('EN_COURS', 'SOUMIS', 'VALIDE', 'ANNULE')),
    CONSTRAINT fk_inventaire_famille    FOREIGN KEY (id_famille)    REFERENCES famille (id_famille),
    CONSTRAINT fk_inventaire_cree_par   FOREIGN KEY (id_cree_par)   REFERENCES utilisateur (id_utilisateur),
    CONSTRAINT fk_inventaire_soumis_par FOREIGN KEY (id_soumis_par) REFERENCES utilisateur (id_utilisateur),
    CONSTRAINT fk_inventaire_valide_par FOREIGN KEY (id_valide_par) REFERENCES utilisateur (id_utilisateur)
);
CREATE INDEX IF NOT EXISTS idx_inventaire_statut ON inventaire (statut);
CREATE INDEX IF NOT EXISTS idx_inventaire_date   ON inventaire (date_ouverture DESC);

CREATE TABLE IF NOT EXISTS inventaire_ligne (
    id_inventaire_ligne INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_inventaire       INTEGER          NOT NULL,
    id_article          INTEGER          NOT NULL,
    stock_theorique     DOUBLE PRECISION NOT NULL,
    quantite_comptee    DOUBLE PRECISION,
    date_comptage       TIMESTAMP,
    prix_unitaire       DOUBLE PRECISION,
    commentaire         TEXT,
    CONSTRAINT inventaire_ligne_pkey PRIMARY KEY (id_inventaire_ligne),
    CONSTRAINT uk_inventaire_ligne_article UNIQUE (id_inventaire, id_article),
    CONSTRAINT fk_inventaire_ligne_inventaire FOREIGN KEY (id_inventaire) REFERENCES inventaire (id_inventaire),
    CONSTRAINT fk_inventaire_ligne_article    FOREIGN KEY (id_article)    REFERENCES article (id_article)
);
CREATE INDEX IF NOT EXISTS idx_inventaire_ligne_article ON inventaire_ligne (id_article);

CREATE TABLE IF NOT EXISTS inventaire_evenement (
    id_inventaire_evenement INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_inventaire  INTEGER     NOT NULL,
    action         VARCHAR(20) NOT NULL,
    id_utilisateur INTEGER,
    date_evenement TIMESTAMP   NOT NULL,
    commentaire    TEXT,
    CONSTRAINT inventaire_evenement_pkey PRIMARY KEY (id_inventaire_evenement),
    CONSTRAINT inventaire_evenement_action_check
        CHECK (action IN ('OUVERTURE', 'SOUMISSION', 'REJET', 'VALIDATION', 'ANNULATION')),
    CONSTRAINT fk_inventaire_evenement_inventaire  FOREIGN KEY (id_inventaire)  REFERENCES inventaire (id_inventaire),
    CONSTRAINT fk_inventaire_evenement_utilisateur FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur)
);
CREATE INDEX IF NOT EXISTS idx_inventaire_evenement_inventaire ON inventaire_evenement (id_inventaire);

ALTER TABLE stock_mere ADD COLUMN IF NOT EXISTS id_inventaire INTEGER;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint c
                   JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
                   WHERE c.contype = 'f' AND c.conrelid = 'stock_mere'::regclass AND a.attname = 'id_inventaire') THEN
        ALTER TABLE stock_mere ADD CONSTRAINT fk_stock_mere_inventaire
            FOREIGN KEY (id_inventaire) REFERENCES inventaire (id_inventaire);
    END IF;
END;
$$;
CREATE INDEX IF NOT EXISTS idx_stock_mere_inventaire ON stock_mere (id_inventaire) WHERE id_inventaire IS NOT NULL;


-- Historique des mouvements : ajustements d'inventaire datés, référencés et attribués au valideur
-- (seule la première branche change par rapport à 2026-11-25_migration_PROD.sql)
CREATE OR REPLACE VIEW v_historique_mouvement_stock AS
 WITH bs_confirme AS (
         SELECT bsf.id_bon_sortie_fille,
            bsf.id_article,
            bsf.quantite_sortie,
            bsm.id_demande_mere,
            bsm.numero_bs,
            COALESCE(bsm.date_confirmation, bsm.date_creation) AS date_sortie
           FROM bon_sortie_fille bsf
             JOIN bon_sortie_mere bsm ON bsm.id_bon_sortie_mere = bsf.id_bon_sortie_mere
          WHERE bsm.statut::text = 'CONFIRME'::text
        ), mouvements AS (
         SELECT sf.id_stock_fille,
            sf.id_article,
                CASE
                    WHEN COALESCE(sf.entree, 0::double precision) > 0::double precision THEN 'ENTREE'::text
                    WHEN COALESCE(sf.sortie, 0::double precision) > 0::double precision THEN 'SORTIE'::text
                    ELSE 'INCONNU'::text
                END AS type_mouvement,
                CASE
                    WHEN COALESCE(sf.entree, 0::double precision) > 0::double precision THEN sf.entree
                    ELSE sf.sortie
                END AS quantite,
                CASE
                    WHEN inv.id_inventaire IS NOT NULL THEN inv.date_cloture
                    WHEN COALESCE(sf.entree, 0::double precision) > 0::double precision THEN bl.date_reception
                    WHEN COALESCE(sf.sortie, 0::double precision) > 0::double precision THEN COALESCE(dm.date_sortie, dm.date_demande)
                    ELSE NULL::timestamp without time zone
                END AS date_mouvement,
            bl.id_bl_mere AS ref_bl_mere,
            dm.id_demande_mere AS ref_demande_mere,
                CASE
                    WHEN inv.id_inventaire IS NOT NULL THEN concat('Inventaire — ', uv.prenom, ' ', uv.nom)::character varying
                    WHEN COALESCE(sf.entree, 0::double precision) > 0::double precision THEN f.nom
                    WHEN COALESCE(sf.sortie, 0::double precision) > 0::double precision THEN concat(u.prenom, ' ', u.nom)::character varying
                    ELSE '-'::character varying
                END AS auteur,
                CASE
                    WHEN inv.id_inventaire IS NOT NULL THEN inv.reference
                    WHEN COALESCE(sf.entree, 0::double precision) > 0::double precision THEN bl.id_bl_mere
                    WHEN COALESCE(sf.sortie, 0::double precision) > 0::double precision THEN dm.id_demande_mere
                    ELSE NULL::character varying
                END AS reference
           FROM stock_fille sf
             JOIN stock_mere sm ON sm.id_stock_mere = sf.id_stock_mere
             LEFT JOIN bon_livraison_mere bl ON bl.id_bl_mere::text = sm.id_bl_mere::text
             LEFT JOIN fournisseur f ON f.id_fournisseur = bl.id_fournisseur
             LEFT JOIN demande_mere dm ON dm.id_demande_mere::text = sm.id_demande_mere::text
             LEFT JOIN utilisateur u ON u.id_utilisateur = dm.id_demandeur
             LEFT JOIN inventaire inv ON inv.id_inventaire = sm.id_inventaire
             LEFT JOIN utilisateur uv ON uv.id_utilisateur = inv.id_valide_par
          WHERE sf.entree > 0::double precision OR sf.sortie > 0::double precision AND sm.id_demande_mere IS NULL
        UNION ALL
         SELECT - bs.id_bon_sortie_fille,
            bs.id_article,
            'SORTIE'::text AS text,
            bs.quantite_sortie,
            bs.date_sortie,
            NULL::character varying AS "varchar",
            dm.id_demande_mere,
            concat(u.prenom, ' ', u.nom)::character varying AS concat,
            bs.numero_bs::character varying AS numero_bs
           FROM bs_confirme bs
             JOIN demande_mere dm ON dm.id_demande_mere::text = bs.id_demande_mere::text
             LEFT JOIN utilisateur u ON u.id_utilisateur = dm.id_demandeur
        UNION ALL
         SELECT sf.id_stock_fille,
            sf.id_article,
            'SORTIE'::text AS text,
            sf.sortie - COALESCE(couvert.quantite, 0::double precision),
            COALESCE(dm.date_sortie, dm.date_demande) AS "coalesce",
            NULL::character varying AS "varchar",
            dm.id_demande_mere,
            concat(u.prenom, ' ', u.nom)::character varying AS concat,
            dm.id_demande_mere
           FROM stock_fille sf
             JOIN stock_mere sm ON sm.id_stock_mere = sf.id_stock_mere
             JOIN demande_mere dm ON dm.id_demande_mere::text = sm.id_demande_mere::text
             LEFT JOIN utilisateur u ON u.id_utilisateur = dm.id_demandeur
             LEFT JOIN LATERAL ( SELECT sum(bs.quantite_sortie) AS quantite
                   FROM bs_confirme bs
                  WHERE bs.id_demande_mere::text = sm.id_demande_mere::text AND bs.id_article = sf.id_article) couvert ON true
          WHERE COALESCE(sf.entree, 0::double precision) <= 0::double precision AND (sf.sortie - COALESCE(couvert.quantite, 0::double precision)) > 0.0001::double precision
        )
 SELECT m.id_stock_fille,
    m.id_article,
    a.code_article,
    a.designation,
    m.type_mouvement,
    m.quantite,
    m.date_mouvement,
    m.ref_bl_mere::character varying(255) AS ref_bl_mere,
    m.ref_demande_mere,
    m.auteur,
    m.reference,
    udm.acronyme AS udm,
    udm.description AS desc_udm
   FROM mouvements m
     JOIN article a ON a.id_article = m.id_article
     LEFT JOIN udm ON udm.id_udm = a.id_udm
  ORDER BY m.date_mouvement DESC;

COMMIT;
