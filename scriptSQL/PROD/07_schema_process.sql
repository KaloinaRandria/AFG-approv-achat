-- ═════════════════════════════════════════════════════════════════════════════
-- 07 — Schéma "process" : tables de l'appli AFG-process dans la base commune
--
-- Phase 2 de docs/plan-migration-referentiel.md. À exécuter EN TANT QUE postgres,
-- connecté à la base commune (ACHAT_APPROV_MIGR pour la répétition, puis
-- ACHAT_APPROV_PREPROD, puis ACHAT_APPROV_PROD).
-- Prérequis : 06_schema_referentiel.sql exécuté sur la même base.
--
-- Crée, VIDES, les tables propres à process (rôles et habilitations, demandes de rôles,
-- procédures, questions, évaluations). Elles n'ont plus de table utilisateur ni direction :
-- leurs clés étrangères pointent vers referentiel.utilisateur et referentiel.service
-- (décisions D1, D3). Les colonnes id_direction gardent leur nom et désignent
-- referentiel.service(id_service).
--
-- Login de l'appli process : process_<environnement>_app (process_preprod_app,
-- process_prod_app…), créé s'il n'existe pas, sans mot de passe : le définir ensuite avec
--   ALTER ROLE process_xxx_app PASSWORD '…';
-- Droits : lecture / écriture sur process, LECTURE SEULE sur referentiel, rien sur public.
--
-- N'affecte pas l'appli achat ni la base PROCESS_PREPROD actuelle : l'appli process continue
-- de tourner sur son ancienne base jusqu'au déploiement de sa nouvelle version (phase 3).
-- En PREPROD, exécuter ensuite scriptSQL/reprise_process_preprod.sql (habilitations).
--
-- Rejouable : tables et droits créés seulement s'ils n'existent pas.
-- ═════════════════════════════════════════════════════════════════════════════

BEGIN;

DO $$
BEGIN
    IF to_regclass('referentiel.utilisateur') IS NULL THEN
        RAISE EXCEPTION 'referentiel.utilisateur introuvable : exécuter d''abord 06_schema_referentiel.sql';
    END IF;
END $$;

CREATE SCHEMA IF NOT EXISTS process AUTHORIZATION postgres;
COMMENT ON SCHEMA process IS
    'Tables de l''appli AFG-process. Utilisateurs et directions : schéma referentiel.';

-- ── Habilitations ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS process.role (
    id_role integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role    varchar(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS process.utilisateur_role (
    id_utilisateur integer NOT NULL REFERENCES referentiel.utilisateur (id_utilisateur),
    id_role        integer NOT NULL REFERENCES process.role (id_role),
    PRIMARY KEY (id_utilisateur, id_role)
);

-- ── Demandes (maker / checker) ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS process.demande_utilisateur (
    id_demande      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actif           boolean       NOT NULL,
    commentaire     varchar(1000),
    date_demande    timestamp(6)  NOT NULL,
    date_traitement timestamp(6),
    mail            varchar(255)  NOT NULL,
    nom             varchar(255),
    prenom          varchar(255),
    statut          varchar(20)   NOT NULL
        CHECK (statut IN ('EN_ATTENTE', 'VALIDEE', 'REJETEE', 'ANNULEE')),
    type            varchar(20)   NOT NULL
        CHECK (type IN ('CREATION', 'MODIFICATION')),
    id_checker      integer REFERENCES referentiel.utilisateur (id_utilisateur),
    id_direction    integer REFERENCES referentiel.service (id_service),
    id_maker        integer NOT NULL REFERENCES referentiel.utilisateur (id_utilisateur),
    id_utilisateur  integer REFERENCES referentiel.utilisateur (id_utilisateur)
);

CREATE TABLE IF NOT EXISTS process.demande_utilisateur_role (
    id_demande integer NOT NULL REFERENCES process.demande_utilisateur (id_demande),
    role       varchar(30),
    UNIQUE (id_demande, role)
);

-- ── Procédures et évaluations ───────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS process.procedures (
    id_procedure     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actif            boolean       NOT NULL DEFAULT true,
    date_mise_a_jour timestamp(6),
    description      varchar(2000),
    fichier_nom      varchar(255),
    fichier_stocke   varchar(255),
    reference        varchar(50)   NOT NULL UNIQUE,
    seuil_reussite   integer       NOT NULL DEFAULT 7,
    titre            varchar(255)  NOT NULL,
    id_direction     integer       NOT NULL REFERENCES referentiel.service (id_service)
);

CREATE TABLE IF NOT EXISTS process.question (
    id_question  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actif        boolean       NOT NULL DEFAULT true,
    enonce       varchar(1000) NOT NULL,
    id_procedure integer       NOT NULL REFERENCES process.procedures (id_procedure)
);

CREATE TABLE IF NOT EXISTS process.choix (
    id_choix    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correct     boolean      NOT NULL,
    libelle     varchar(500) NOT NULL,
    id_question integer      NOT NULL REFERENCES process.question (id_question)
);

CREATE TABLE IF NOT EXISTS process.evaluation (
    id_evaluation  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_debut     timestamp(6) NOT NULL,
    date_fin       timestamp(6),
    nb_questions   integer      NOT NULL,
    note           integer,
    resultat       varchar(30) CHECK (resultat IN ('ACQUIS', 'FORMATION_REQUISE')),
    seuil          integer      NOT NULL,
    statut         varchar(20)  NOT NULL CHECK (statut IN ('EN_COURS', 'TERMINEE')),
    id_procedure   integer      NOT NULL REFERENCES process.procedures (id_procedure),
    id_utilisateur integer      NOT NULL REFERENCES referentiel.utilisateur (id_utilisateur)
);
CREATE INDEX IF NOT EXISTS idx_evaluation_utilisateur_procedure
    ON process.evaluation (id_utilisateur, id_procedure);

CREATE TABLE IF NOT EXISTS process.evaluation_reponse (
    id_evaluation_reponse integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correct       boolean,
    ordre         integer NOT NULL,
    id_choix      integer REFERENCES process.choix (id_choix),
    id_evaluation integer NOT NULL REFERENCES process.evaluation (id_evaluation),
    id_question   integer NOT NULL REFERENCES process.question (id_question)
);

-- ── Login de l'appli process et droits ──────────────────────────────────────
DO $$
DECLARE
    v_base  text := current_database();
    v_login text := replace(lower(current_database()), 'achat_approv', 'process') || '_app';
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = v_login) THEN
        EXECUTE format('CREATE ROLE %I LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION', v_login);
        RAISE NOTICE 'Login % créé : définir son mot de passe avec ALTER ROLE % PASSWORD ''…'';', v_login, v_login;
    END IF;

    EXECUTE format('GRANT CONNECT, TEMPORARY ON DATABASE %I TO %I', v_base, v_login);

    -- process : lecture / écriture des données
    EXECUTE format('GRANT USAGE ON SCHEMA process TO %I', v_login);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE, REFERENCES ON ALL TABLES IN SCHEMA process TO %I', v_login);
    EXECUTE format('GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA process TO %I', v_login);
    EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA process '
                || 'GRANT SELECT, INSERT, UPDATE, DELETE, REFERENCES ON TABLES TO %I', v_login);
    EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA process '
                || 'GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO %I', v_login);

    -- referentiel : lecture seule (seule l'appli achat y écrit, décision D1)
    EXECUTE format('GRANT USAGE ON SCHEMA referentiel TO %I', v_login);
    EXECUTE format('GRANT SELECT ON ALL TABLES IN SCHEMA referentiel TO %I', v_login);
    EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA referentiel '
                || 'GRANT SELECT ON TABLES TO %I', v_login);

    -- Noms sans préfixe : "role" = process.role (et non public.role de l'appli achat)
    EXECUTE format('ALTER ROLE %I IN DATABASE %I SET search_path = process, referentiel', v_login, v_base);
END $$;

-- Le login de l'appli achat n'a aucun droit sur process (rien à faire : aucun GRANT).

COMMIT;

-- ── Contrôles ───────────────────────────────────────────────────────────────
-- 1. Les 9 tables de process
SELECT tablename AS table_process FROM pg_tables WHERE schemaname = 'process' ORDER BY 1;

-- 2. Droits du login process (attendu : process = écriture, referentiel = lecture seule,
--    public.utilisateur_role de l'achat = aucun droit)
SELECT r.rolname AS login,
       has_table_privilege(r.rolname, 'process.utilisateur_role', 'INSERT')       AS ecrit_process,
       has_table_privilege(r.rolname, 'referentiel.utilisateur', 'SELECT')        AS lit_referentiel,
       has_table_privilege(r.rolname, 'referentiel.utilisateur', 'INSERT')        AS ecrit_referentiel,
       has_table_privilege(r.rolname, 'public.utilisateur_role', 'SELECT')        AS lit_achat
FROM pg_roles r
WHERE r.rolname = replace(lower(current_database()), 'achat_approv', 'process') || '_app';
